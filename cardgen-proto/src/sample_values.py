def has_real_data(text: str) -> bool:
    """hint 已含数字即视为真实数据（如"26°C"），不替换。"""
    return any(ch.isdigit() for ch in text)


def infer_sample(hint: str):
    """按关键词白名单推断样本值；未命中返回 None。

    **最长匹配优先**（不依赖表内顺序）——"剩余电量" 必须命中 `剩余电` 而不是 `剩余`，
    "电池温度" 必须命中 `电池温度` 而不是 `温度`。此前依赖"更具体的词排在前面"的
    隐式约定，一旦插错位置就会把 68% 映射成"30天"（2026-10-16 实测踩坑），
    改为最长匹配后该 bug 类不再可能出现。
    """
    if has_real_data(hint):
        return None
    # 匹配强度：整词 > 前缀/后缀 > 中间包含（且中间包含要求重合度 > 50%）。
    # 收紧中间包含的原因（2026-10-19 实测）："会议发起人" 含 "会议" 被映射成活动名
    # "项目例会"、"是否重要日程" 含 "日程" 同样被抢走、"睡眠质量" 含 "睡眠" 变成时长。
    # 中文复合词中心语在右，前后缀匹配比任意包含可靠得多。
    best_key, best_val = None, None
    for kw, v in SAMPLE_MAP:
        if kw == hint:
            return v                              # 整词命中，直接返回
        pref = hint.startswith(kw)
        suff = hint.endswith(kw)
        if not (pref or suff):
            if kw not in hint or len(kw) / len(hint) <= 0.5:
                continue                          # 只是"沾边"，不算命中
        # 同长度时**后缀优先**：中文中心语在右侧——"会员折扣" 的中心语是"折扣"，
        # 若让前缀"会员"(会员到期日) 赢，折扣会被替换成日期（2026-10-19 实测回归）。
        key = (len(kw), 1 if suff else 0)
        if best_key is None or key > best_key:
            best_key, best_val = key, v
    return best_val
